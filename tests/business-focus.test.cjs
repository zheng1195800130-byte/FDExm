'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),path=require('node:path'),Zip=require('adm-zip');
const core=process.env.FDE_CORE_TEST_ROOT||path.resolve(__dirname,'../src/core');
const focus=require(process.env.FDE_BUSINESS_FOCUS_MODULE||path.join(core,'business-focus.cjs'));
const {workProject,organizedReport}=require(path.join(core,'daily-report.cjs'));
const {selectRecords,createWorkbook}=require(path.join(core,'work-record-export.cjs'));
const date='2026-10-23',business={id:'business',date,issueKey:'fee',title:'修复金额核对',cause:'空金额导致计算异常',action:'修复空值处理并同步两个EasyClaw项目',result:'金额报错已修复并同步两个EasyClaw项目，102项测试通过，版本1.0.31未改动，未重跑整份账单，未推送GitLab。',status:'待验证',autoGenerated:true};
const technical={id:'technical',date,issueKey:'sync',title:'同步到EasyClaw',action:'同步失败',result:'未推送GitLab',autoGenerated:true};
test('混合内容只去掉内部交付状态，保留业务修复和真实验证限制',()=>{
  assert.equal(focus.cleanText(business.action),'修复空值处理');
  assert.equal(focus.cleanText(business.result),'金额报错已修复，102项测试通过，未重跑整份账单。');
  for(const text of ['GitLab未同步','尚未推送GitLab','EasyClaw同步失败','同步两个EasyClaw项目','EasyClaw更新失败','宿主实际界面待重开应用验证','是否需要同步到EasyClaw？','将当前工具同步到EasyClaw'])assert.equal(focus.cleanText(text),'',text);
  assert.equal(focus.cleanText('自测通过（未推送GitLab），客户尚未验收。'),'自测通过，客户尚未验收。');
  assert.equal(focus.cleanText('EasyClaw同步失败但金额已修复'),'金额已修复');
});
test('工具名称属于实际业务功能时保留，普通业务同步不误删',()=>{
  for(const text of ['支持从GitLab同步客户需求','将工作记录同步到EasyClaw业务表','修复EasyClaw登录与账号隔离','EasyClaw登录功能待客户验收','订单与提单同步失败，等待ERP接口确认。','客户尚未测试真实账单。'])assert.equal(focus.cleanText(text),text);
});
test('四类结果及历史版本使用一致的业务视图，原档案保持不变',()=>{
  const report={date,autoArchived:true,text:'修复金额核对，未推送GitLab。'};
  const requirement={requirementKey:'fee',title:'核对金额',description:'修复分摊；EasyClaw同步失败',questions:['收费标准如何确认？','是否重启EasyClaw？']};
  const confirmations=[{confirmationKey:'biz',scenario:'金额口径不一致',question:'收费口径如何处理？',status:'待确认'},{confirmationKey:'ops',scenario:'应用交付',question:'是否同步到EasyClaw？',status:'待确认'}];
  const project={records:[business,technical],requirements:[requirement],requirementConfirmations:confirmations,reports:[report],dailyDesk:{overview:{scene:'核对账单',progress:'金额已修复，未推送GitLab',nextAction:'同步EasyClaw',blocker:'GitLab未同步'},days:{[date]:{digest:{reportText:report.text}}}},dailyHistory:{[date]:[{id:'v1',records:[business,technical],requirements:[requirement],confirmations,report,digest:{reportText:report.text}}]},codex:{dailySummaries:[{date,items:[business,technical]}]}};
  const before=JSON.stringify(project),view=workProject(project);
  assert.equal(view.records.length,1);assert.equal(view.records[0].status,'待验证');assert.deepEqual(view.requirements[0].questions,['收费标准如何确认？']);assert.equal(view.requirementConfirmations.length,1);
  assert.equal(view.dailyDesk.overview.blocker,'');assert.equal(view.dailyDesk.overview.nextAction,'');assert.equal(view.dailyDesk.overview.progress,'金额已修复');
  assert.ok(!/GitLab|EasyClaw/.test(JSON.stringify([view.records,view.reports,view.dailyHistory,view.codex])));assert.equal(JSON.stringify(project),before);
});
test('人工记录、需求和日报不自动改写',()=>{
  const manual={...business,manual:true},report={autoArchived:false,text:'人工填写：GitLab尚未同步'};
  const view=focus.project({records:[manual],requirements:[{manual:true,title:'手工需求',description:'同步EasyClaw'}],reports:[report]});
  assert.deepEqual(view.records[0],manual);assert.equal(view.requirements[0].description,'同步EasyClaw');assert.deepEqual(view.reports[0],report);
});
test('导出与页面一致，跨日日期和所选旧版保留，纯同步事项不导出',()=>{
  const project={records:[business,technical],dailyHistory:{[date]:[{id:'old',records:[{...business,title:'金额核对旧版'},technical]}]}};
  const output=selectRecords(project,{startDate:date,endDate:date,versionId:'old'});assert.equal(output.length,1);assert.equal(output[0].title,'金额核对旧版');assert.equal(output[0].date,date);
  const xml=new Zip(createWorkbook(output)).readAsText('xl/worksheets/sheet1.xml');assert.ok(!/GitLab|EasyClaw/.test(xml));assert.match(xml,/未重跑整份账单/);
});
test('无新增对话时读取旧日报也不带回工具交付状态',()=>{
  const row={...business,sourceIds:['turn:one']};
  assert.equal(organizedReport('样例',{items:[row],reportText:''},{},{hasTurns:false,previousDigest:{workEvidenceVersion:2,reportText:'已修复金额，未推送GitLab。'}}),'已修复金额。');
});
