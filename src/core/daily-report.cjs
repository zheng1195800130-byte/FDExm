'use strict';
// A document's presence or modification time is not evidence of work today.
function materialOnly(item) {
  if ((item.turnIds || []).length || (item.sourceIds || []).some(id => id.startsWith('turn:'))) return false;
  if ((item.sourceIds || []).length) return item.sourceIds.every(id => id.startsWith('file:'));
  const refs=String(item.sourceRef || '').split('\n').filter(Boolean);
  return refs.length>0 && refs.every(ref=>!/#turn=/.test(ref) && /\.(?:xlsx?|docx?|pptx?|pdf|txt|md|csv|json|html?)(?:\s|$)/i.test(ref));
}
function workReport(name, items) {
  const short=(text,max)=>String(text||'').replace(/\d+\s*项[^，。；]*(?:测试|验证)[^，。；]*通过[，。；]?/g,'').replace(/\s+/g,' ').trim().replace(/[。；;]+$/,'').slice(0,max);
  const rows=items.filter(item=>item.manual||item.confirmed||!materialOnly(item)).map(item=>{
    const title=short(item.title,100),action=short(item.action,180),result=short(item.result,180);
    return `${title}${action&&action!==title?'：'+action:''}${result&&result!==action?'；'+result:''}。`;
  });
  return rows.length?`${name}——${rows.join('\n\n')}`:'';
}
function organizedReport(name, result, output, {hasTurns, previousDigest}={}) {
  const items=result.items.filter(item=>!materialOnly(item));
  if(!items.length)return '';
  if(!hasTurns && previousDigest?.workEvidenceVersion===2)return previousDigest.reportText || workReport(name,items);
  const keys=output.reportIssueKeys;
  const known=new Set(items.flatMap(item=>[item.issueKey,...item.relatedIssueKeys||[]]));
  const covered=Array.isArray(keys)&&keys.every(key=>known.has(key))&&items.every(item=>[item.issueKey,...item.relatedIssueKeys||[]].some(key=>keys.includes(key)));
  return hasTurns&&covered&&result.reportText.trim()?result.reportText:workReport(name,items);
}
function workProject(project) {
  const protectedWork=(date,item)=>(project.records||[]).some(record=>record.date===date&&(record.manual||record.confirmed)&&[record.issueKey,...record.relatedIssueKeys||[]].some(key=>key&&[item.issueKey,...item.relatedIssueKeys||[]].includes(key)));
  return {...project,
    ...(project.records?{records:project.records.filter(record=>record.manual||record.confirmed||!(record.managedBy==='codex-auto'||record.autoGenerated)||!materialOnly(record))}:{}),
    ...(project.codex?{codex:{...project.codex,dailySummaries:(project.codex.dailySummaries||[]).map(summary=>({...summary,items:summary.items.filter(item=>!materialOnly(item)||protectedWork(summary.date,item))}))}}:{})};
}
module.exports={materialOnly,workReport,organizedReport,workProject};
